#!/usr/bin/env bash
# Prints a hash of build/libdrums.a; with --write, keys it into the cgo package
# that links the archive. Go's cache sees the -L/-l flags, never the archive's
# bytes, so without this a rebuilt libdrums.a is silently not relinked.
set -euo pipefail
write=0
if [[ "${1:-}" == "--write" ]]; then write=1; shift; fi
root="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
hash="$(sha256sum "$root/build/libdrums.a" | cut -c1-16)"
if [[ $write == 1 ]]; then
  gen="$root/src/go/internal/audio/clib_hash.gen.go"
  want="$(printf '%s\n' '// Code generated by scripts/clib-hash.sh. DO NOT EDIT.' '' '//go:build !test && !js' '' 'package audio' '' "// #cgo CFLAGS: -DBEATMO_CLIB_HASH=$hash" 'import "C"')"
  if [[ ! -f "$gen" || "$(cat "$gen")" != "$want" ]]; then
    printf '%s\n' "$want" > "$gen"
  fi
fi
echo "$hash"
