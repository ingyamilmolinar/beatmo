//go:build !js

// gen-synth-abi emits the JS write loop (-o ../js/synth_param_abi.gen.js) and the C struct (-c -o
// ../c/modular_params.gen.h) from one table (modular_fields.go), so they cannot drift. -o writes only after success: never
// redirect into the header, the shell truncates it before the cgo build that #includes it.
package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"github.com/ingyamilmolinar/beatmo/internal/audio"
)

var outPath string

func main() {
	header := false
	for i := 1; i < len(os.Args); i++ {
		switch os.Args[i] {
		case "-c":
			header = true
		case "-o":
			if i+1 < len(os.Args) {
				outPath = os.Args[i+1]
				i++
			}
		}
	}
	if header {
		emit(cHeader())
		return
	}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/gen-synth-abi. DO NOT EDIT.\n")
	buf.WriteString("//\n")
	buf.WriteString("// Source of truth: src/go/internal/audio/modular_fields.go\n")
	buf.WriteString("// Regenerate: cd src/go && go run ./cmd/gen-synth-abi -o ../js/synth_param_abi.gen.js\n")

	// ── Modular voice block ──────────────────────────────────────────────────
	modSchema := audio.ModularParamSchema()

	buf.WriteString("\n")
	buf.WriteString("// MODULAR_PARAM_COUNT is the number of fields in the C modular_params struct\n")
	buf.WriteString("// (src/c/modular.h) — the unified modular synth voice's param block, the only\n")
	buf.WriteString("// param block that crosses the ABI.\n")
	fmt.Fprintf(&buf, "export const MODULAR_PARAM_COUNT = %d;\n\n", len(modSchema))

	buf.WriteString("// MODULAR_PARAM_INDEX maps a modular knob name to its struct-member index.\n")
	buf.WriteString("// Table cells are not listed (see MODULAR_PARAM_TABLES).\n")
	buf.WriteString("export const MODULAR_PARAM_INDEX = Object.freeze({\n")
	for i, name := range modSchema {
		if strings.Contains(name, "[") {
			continue
		}
		fmt.Fprintf(&buf, "  %s: %d,\n", jsKey(name), i)
	}
	buf.WriteString("});\n\n")

	buf.WriteString("// MODULAR_PARAM_TABLES maps a table column to [first struct index, rows]:\n")
	buf.WriteString("// row i of the column lives at index first + i.\n")
	buf.WriteString("export const MODULAR_PARAM_TABLES = Object.freeze({\n")
	index := audio.ModularParamSchemaIndexMap()
	for _, f := range audio.ModularFieldsForCodegen() {
		if f.Rows > 0 {
			fmt.Fprintf(&buf, "  %s: [%d, %d],\n", jsKey(f.Name), index[f.Name+"[0]"], f.Rows)
		}
	}
	buf.WriteString("});\n")

	emit(buf.Bytes())
}

func emit(b []byte) {
	if outPath != "" {
		tmp := outPath + ".tmp"
		if err := os.WriteFile(tmp, b, 0o644); err == nil {
			if err = os.Rename(tmp, outPath); err == nil {
				return
			}
		}
		fmt.Fprintf(os.Stderr, "gen-synth-abi: cannot write %s\n", outPath)
		os.Exit(1)
	}
	if _, err := os.Stdout.Write(b); err != nil {
		fmt.Fprintf(os.Stderr, "gen-synth-abi: write failed: %v\n", err)
		os.Exit(1)
	}
}

// cHeader renders modular_params (a double per global row, double[N] per slot row) with a static assert that the
// struct is a dense array of doubles: the Go and JS marshals copy a flat block into it.
func cHeader() []byte {
	var b bytes.Buffer
	b.WriteString("/* Code generated by cmd/gen-synth-abi -c. DO NOT EDIT.\n")
	b.WriteString(" * Source of truth: src/go/internal/audio/modular_fields.go\n")
	b.WriteString(" * Regenerate: cd src/go && go run ./cmd/gen-synth-abi -c -o ../c/modular_params.gen.h */\n")
	b.WriteString("#ifndef MODULAR_PARAMS_GEN_H\n#define MODULAR_PARAMS_GEN_H\n\n")
	fmt.Fprintf(&b, "#define MODULAR_PARAM_COUNT %d\n\n", len(audio.ModularParamSchema()))
	// Slots per block: a family voice in slot k reads its fields only when
	// k < MODULAR_<BLOCK>_SLOTS (the engine renders nothing otherwise).
	seen := map[string]bool{}
	for _, f := range audio.ModularFieldsForCodegen() {
		if f.Slots > 0 && !seen[f.Block] {
			seen[f.Block] = true
			fmt.Fprintf(&b, "#define MODULAR_%s_SLOTS %d\n", strings.ToUpper(f.Block), f.Slots)
		}
		if f.Rows > 0 {
			fmt.Fprintf(&b, "#define MODULAR_%s_ROWS %d\n", strings.ToUpper(f.Name), f.Rows)
		}
	}
	b.WriteString("\n")
	b.WriteString("typedef struct {\n")
	block := ""
	for _, f := range audio.ModularFieldsForCodegen() {
		if f.Block != block {
			if block != "" {
				b.WriteString("\n")
			}
			fmt.Fprintf(&b, "    /* ── %s ── */\n", f.Block)
			block = f.Block
		}
		decl := "double " + f.Name + ";"
		if f.Rows > 0 {
			decl = fmt.Sprintf("double %s[%d];", f.Name, f.Rows)
		} else if f.Slots > 0 {
			decl = fmt.Sprintf("double gen_%s[%d];", f.Name, f.Slots)
		}
		if f.Doc != "" {
			fmt.Fprintf(&b, "    %s /* %s */\n", decl, strings.ReplaceAll(f.Doc, "*/", "* /"))
		} else {
			fmt.Fprintf(&b, "    %s\n", decl)
		}
	}
	b.WriteString("} modular_params;\n\n")
	b.WriteString("_Static_assert(sizeof(modular_params) == MODULAR_PARAM_COUNT * sizeof(double),\n")
	b.WriteString("               \"modular_params must be a dense array of doubles\");\n\n")
	b.WriteString("#endif\n")
	return b.Bytes()
}

// jsKey returns name quoted only if necessary so the output stays readable
// (e.g. "pitch" appears as `pitch:` not `"pitch":`).
func jsKey(name string) string {
	if isIdent(name) {
		return name
	}
	return `"` + strings.ReplaceAll(name, `"`, `\"`) + `"`
}

func isIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		ok := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_' || r == '$'
		if i > 0 {
			ok = ok || (r >= '0' && r <= '9')
		}
		if !ok {
			return false
		}
	}
	return true
}
