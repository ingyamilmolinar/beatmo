// Command gen-fundamentals emits internal/audio/instrument_fundamentals.gen.go:
// the base sounding fundamental of every built-in instrument, so the UI can name
// the note a node sounds for EVERY instrument rather than only the curated
// melodic set.
//
// Why generated rather than computed at runtime: resolving a fundamental means
// rendering the voice through the C DSP and running YIN over it. That is far too
// expensive for nodeNoteLabel (once per visible node per FRAME), and the real
// render path exists only in the native cgo build — under `-tags test` it is a
// stub and on js/wasm it is absent, so a runtime measurement would silently
// disagree across platforms. Baking it makes the answer one map lookup and
// identical everywhere.
//
// Regenerate with `make gen-fundamentals` (needs CGO + build/libdrums.a).
// TestInstrumentFundamentalsUpToDate re-measures and fails when the committed
// table drifts.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"text/template"

	"github.com/ingyamilmolinar/beatmo/internal/audio/fingerprint"
	"github.com/ingyamilmolinar/beatmo/internal/instrument/roster"
)

func main() {
	report := flag.Bool("report", false, "print a human-readable table instead of Go source")
	out := flag.String("o", "", "write Go source here instead of stdout")
	flag.Parse()

	ms, err := MeasureAll()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-fundamentals:", err)
		os.Exit(1)
	}
	if *report {
		printReport(os.Stdout, ms)
		return
	}
	src, err := Render(ms)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-fundamentals:", err)
		os.Exit(1)
	}
	if *out == "" {
		os.Stdout.Write(src)
		return
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen-fundamentals:", err)
		os.Exit(1)
	}
}

// MeasureAll resolves every built-in instrument in roster.All order.
// It collects ALL contradictions before failing, so one regeneration reports
// every disagreement rather than stopping at the first.
func MeasureAll() ([]Measurement, error) {
	var ms []Measurement
	var errs []string
	for _, id := range roster.All {
		m, err := measure(id)
		if err != nil {
			errs = append(errs, err.Error())
			continue
		}
		ms = append(ms, m)
	}
	if len(errs) > 0 {
		sort.Strings(errs)
		return nil, fmt.Errorf("%d instrument(s) failed:\n  %s", len(errs), joinLines(errs))
	}
	return ms, nil
}

func joinLines(s []string) string {
	b := &bytes.Buffer{}
	for i, l := range s {
		if i > 0 {
			b.WriteString("\n  ")
		}
		b.WriteString(l)
	}
	return b.String()
}

func printReport(w *os.File, ms []Measurement) {
	bySource := map[Source]int{}
	fmt.Fprintf(w, "%-24s %-13s %9s %9s %6s %-16s %s\n", "id", "source", "baseHz", "measHz", "conf", "declared", "note")
	for _, m := range ms {
		bySource[m.Source]++
		decl := "-"
		if m.DeclaredKey != "" {
			decl = fmt.Sprintf("%s=%.0f", m.DeclaredKey, m.DeclaredHz)
		}
		// Surfacing the floor rejection is the difference between "why is the
		// 808 kick F1 and not G1?" being a mystery and being an explanation:
		// its 50.00 Hz reading is the detector's ceiling on how low it can see,
		// not a measurement of the voice.
		note := ""
		switch {
		case m.FloorPinned:
			note = fmt.Sprintf("measurement rejected: pinned at the %d Hz detector floor", fingerprint.F0SearchMinHz)
		case m.Unsupported:
			note = fmt.Sprintf("measurement rejected: no partial below %.1fx f0 — not a pitch", m.LowestPartialRatio)
		}
		fmt.Fprintf(w, "%-24s %-13s %9.2f %9.2f %6.3f %-16s %s\n",
			m.ID, m.Source, m.BaseHz, m.MeasuredHz, m.Confidence, decl, note)
	}
	fmt.Fprintf(w, "\ntotal=%d measured=%d declared=%d voice_freq=%d none=%d (reliable conf >= %.2f)\n",
		len(ms), bySource[SourceMeasured], bySource[SourceDeclared],
		bySource[SourceVoiceFreq], bySource[SourceNone], fingerprint.F0ReliableConfidence)
}

var tmpl = template.Must(template.New("f").Parse(`// Code generated by cmd/gen-fundamentals; DO NOT EDIT.
//
// The base sounding fundamental of every built-in instrument, measured by
// rendering the voice at node pitch 0 with its shipped parameters and running
// DetectF0Detailed over the result (see cmd/gen-fundamentals for the precedence
// between a measured and a declared value, and for the cross-check that fails
// regeneration when the two contradict each other).
//
// "Base" means at the instrument's DEFAULT parameters. A live edit to a
// pitch-bearing knob is applied on top of this as a delta at read time
// (InstrumentPitchInfo), so the displayed note still tracks synth edits with
// nothing to invalidate here.
//
// Regenerate with ` + "`make gen-fundamentals`" + `.

package audio

import "github.com/ingyamilmolinar/beatmo/internal/instrument"

// instrumentFundamental is one instrument's base fundamental plus the evidence
// behind it, kept so a surprising note name can be explained.
type instrumentFundamental struct {
	// baseHz is the sounding fundamental at default params, or 0 when the
	// instrument is genuinely unpitched (noise) and gets no note name.
	baseHz float64
	// source is "measured", "declared", "voice_freq_hz", or "none".
	source string
	// confidence is DetectF0Detailed's 0..1 verdict on the measurement, kept
	// even when it lost to a declared value so the choice stays auditable.
	confidence float64
}

// instrumentFundamentals maps instrument id -> its base fundamental.
var instrumentFundamentals = map[instrument.ID]instrumentFundamental{
{{- range .}}
	{{printf "%q" .ID}}: { {{printf "%.4f" .BaseHz}}, {{printf "%q" .Source}}, {{printf "%.3f" .Confidence}}},
{{- end}}
}
`))

// Render turns the measurements into gofmt'd Go source.
func Render(ms []Measurement) ([]byte, error) {
	buf := &bytes.Buffer{}
	if err := tmpl.Execute(buf, ms); err != nil {
		return nil, err
	}
	return format.Source(buf.Bytes())
}
